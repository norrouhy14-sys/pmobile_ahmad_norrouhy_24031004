void main(){
  var nilai = 'c';
  switch (nilai) {
    case 'a':
      print('anda lulus dengan baik');
      break;
    case 'b':
      print('anda lulus dengan cukup');
      break;
    case 'c' :
      print('anda lulus dengan kurang');
      break;
    default:
      print('nilai tidak diketahui');
  }
}